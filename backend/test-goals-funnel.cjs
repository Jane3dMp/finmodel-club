// Воронка спидометров «Набора»: _goalsFunnel. Запуск: node backend/test-goals-funnel.cjs
//
// 20.08.2026 Жанна: «эти 502 — это кто?», и следом «майских считай тоже, конечно, они же
// вернулись и подтвердили». Спидометры «Подтвердили/Отказ/Думают» считались ТОЛЬКО среди
// не купивших майский — оплативших не спрашивали «планируете ли», вот их и вынесли. Из-за
// этого набор выглядел хуже, чем есть, и нижние спидометры расходились с верхней полосой,
// где майские всегда учитывались.
//
// Проверяем главное: каждая запись попадает РОВНО В ОДНУ корзину (подтвердил / отказ /
// думает / молчит-без-ответа), оплата считается подтверждением, а отказ перевешивает оплату.
//
// Проверяется НАСТОЯЩИЙ код из index.html: функция вырезается из файла и выполняется как есть.
const fs = require('fs');
const path = require('path');

let bad = 0;
function check(name, ok, detail) {
  if (!ok) bad++;
  console.log((ok ? '  ok   ' : ' ПЛОХО ') + name + (ok || !detail ? '' : ': ' + detail));
}

const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const m = html.match(/\nfunction _goalsFunnel\(\)\s*\{[\s\S]*?\n\}/m);
if (!m) { console.log('не найдено: _goalsFunnel'); process.exit(1); }

// _nameKey дедуплицирует детей внутри группы по ПОЛНОМУ ФИО (тёзки — разные дети)
function run(grid) {
  const ctx = {
    S: { grid },
    kidsOf: l => (Array.isArray(l.kids) ? l.kids : []),
    _nameKey: n => String(n || '').trim().toLowerCase().replace(/\s+/g, ' '),
  };
  return new Function('ctx', 'with (ctx) { ' + m[0] + '\n return _goalsFunnel(); }')(ctx);
}
const les = (group, kids) => ({ day: 2, start: '10:00', course: 'Лепка', group, kids });

// ---- одна группа, по одному представителю каждого состояния ----
const F = run([les('Лепка №1', [
  { n: 'Оплатил Олег', may: true },                          // оплатил майский — подтвердил
  { n: 'Ответил Артём', vbReply: 'yes' },                    // ответил «да» — подтвердил
  { n: 'Отказ Оксана', vbReply: 'no' },                      // ответ «отказ»
  { n: 'Крестик Кирилл', no: true },                         // ❌ «не придёт»
  { n: 'Думает Дима', vbReply: 'maybe' },                    // думает
  { n: 'Молчит Мария' },                                     // ответа нет
  { n: 'Передумал Пётр', may: true, vbReply: 'no' },         // заплатил, но отказался
])]);

check('записей столько же, сколько детей в группе', F.records === 7, 'records=' + F.records);
check('оплата майского считается подтверждением', F.confirmed === 2,
  'подтвердили=' + F.confirmed + ' (ожидались Олег и Артём)');
check('отказ перевешивает оплату майского', F.refused === 3,
  'отказ=' + F.refused + ' (Оксана, Кирилл и передумавший Пётр)');
check('думают считаются отдельно', F.maybeN === 1);
// оплативший майский НЕ молчит: он уже подтвердил деньгами, дожимать его незачем.
// Иначе он попадал бы и в «подтвердили», и в «молчат», и подписи перестали бы сходиться.
check('молчат — только неопределившиеся без ответа', F.silent === 1,
  'молчат=' + F.silent + ' (ожидалась одна Мария)');
check('молчат + думают = ещё не определились', F.silent + F.maybeN === F.pending,
  F.silent + '+' + F.maybeN + ' vs ' + F.pending);
check('корзины не пересекаются: подтв + отказ + думают + молчат = записи',
  F.confirmed + F.refused + F.maybeN + (F.records - F.confirmed - F.refused - F.maybeN) === F.records);
check('«ещё не определились» = думают + молчат без ответа', F.pending === 2,
  'pending=' + F.pending);
check('определившиеся + не определившиеся = все записи',
  F.confirmed + F.refused + F.pending === F.records);
check('купивших майский видно отдельно', F.paid === 2, 'paid=' + F.paid);
check('не купивших майский — остальные', F.nonMay === 5);

// ---- то, ради чего правка: спидометр не должен занижать набор ----
// Раньше знаменатель = только не-майские, ответившие да/нет. Теперь = все определившиеся.
const answered = F.confirmed + F.refused;
check('в знаменатель спидометра попали и майские', answered === 5,
  'определившихся=' + answered + ' (раньше было бы 3: майских не считали)');
check('доля подтвердивших считается от определившихся',
  Math.round(F.confirmed / answered * 100) === 40);

// ---- ребёнок на двух курсах = две записи, внутри группы дедуп ----
const F2 = run([
  les('Лепка №1', [{ n: 'Иванов Иван', may: true }, { n: 'Иванов Иван', may: true }]),  // дубль в группе
  les('Роблокс №1', [{ n: 'Иванов Иван', vbReply: 'yes' }]),
]);
check('дубль внутри группы схлопывается', F2.records === 2, 'records=' + F2.records);
check('ребёнок на двух курсах даёт две записи', F2.confirmed === 2);
check('уникальных детей — один', F2.unique === 1, 'unique=' + F2.unique);
check('мест на ребёнка = записи ÷ уникальных', Math.abs(F2.perChild - 2) < 0.001);

// ---- тёзки не сливаются ----
const F3 = run([les('Лепка №1', [
  { n: 'Полонников Даниил Ильич', vbReply: 'yes' },
  { n: 'Полонников Даниил Петрович', vbReply: 'no' },
])]);
check('тёзки — разные записи', F3.records === 2 && F3.confirmed === 1 && F3.refused === 1);

// ---- один ребёнок в группе стоит дважды с разными ответами: берём самый весомый ----
const F4 = run([les('Лепка №1', [
  { n: 'Спорный Семён', vbReply: 'maybe' },
  { n: 'Спорный Семён', vbReply: 'yes' },
])]);
check('из двух ответов одного ребёнка берётся более весомый', F4.confirmed === 1 && F4.maybeN === 0);

// ---- пустое расписание ----
const F5 = run([]);
check('пустое расписание: всё по нулям, без падения',
  F5.records === 0 && F5.confirmed === 0 && F5.pending === 0 && F5.perChild === 0);

// ---- отправленные сообщения считаются по всем записям, не только по не-майским ----
const F6 = run([les('Лепка №1', [
  { n: 'Оплатил Олег', may: true, vbSent: true },
  { n: 'Молчит Мария', vbSent: true },
  { n: 'Ничего Никита' },
])]);
check('отправлено считается и по майским', F6.sent === 2, 'sent=' + F6.sent);
check('оплативший майский не числится молчащим', F6.silent === 2 && F6.confirmed === 1,
  'молчат=' + F6.silent + ' (Мария и Никита), подтвердили=' + F6.confirmed);

console.log(bad ? ('\nПРОВАЛЕНО проверок: ' + bad) : '\nВсе проверки прошли.');
process.exit(bad ? 1 : 0);
