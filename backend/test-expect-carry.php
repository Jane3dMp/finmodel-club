<?php
// Что пересчёт дня обязан НЕ затирать в дневной строке «Реализации».
// Запуск: php backend/test-expect-carry.php
//
// Почему это отдельный тест. alfa_realization_upsert ходит в Alfa и в четыре файла — в изоляции
// её не прогнать. Но правило «что переносим из старой строки» — чистое, и цена ошибки высокая:
// замороженное «ожидалось» (expect) — ЕДИНСТВЕННОЕ, что нельзя пересчитывать. planned падает в
// ноль по мере проведения занятий, и к концу недели сравнивать факт было бы не с чем.
//
// ⚠️ Живой дефект (найден разбором 09.09.2026): переносились только expect и expectTs, а
// expectSrc — нет. Из-за этого 🧩-реконструкция («восстановлено по регулярному расписанию»,
// alfa_expect_rebuild_week) переобувалась в 🔒 «зафиксировано вовремя» при первом же пересчёте
// дня. Само собой: ночной cron ходит 7 дней назад, по воскресеньям 30 — восстановленная неделя
// теряла пометку в течение недели, и интерфейс начинал выдавать реконструкцию за снимок.
// Точность у них разная, и код это сам оговаривает подсказкой — значит признак обязан жить.
declare(strict_types=1);

$bad = 0;
function ok(string $name, $got, $want): void {
    global $bad;
    $good = $got === $want;
    if (!$good) $bad++;
    echo ($good ? "✓ " : "✗ ") . $name . ' = ' . json_encode($got, JSON_UNESCAPED_UNICODE)
       . ($good ? '' : ' ≠ ' . json_encode($want, JSON_UNESCAPED_UNICODE)) . "\n";
}
function yes(string $name, bool $cond, string $detail = ''): void {
    global $bad;
    if (!$cond) $bad++;
    echo ($cond ? "✓ " : "✗ ") . $name . ($cond || $detail === '' ? '' : ': ' . $detail) . "\n";
}

/* --- вырезаем НАСТОЯЩУЮ функцию из lib.php --- */
$lib = file_get_contents(__DIR__ . '/../api/alfa/lib.php');
if (!preg_match('/\nfunction alfa_expect_carry\(.*?\n\}/s', $lib, $m)) {
    echo "не найдено в lib.php: alfa_expect_carry\n"; exit(1);
}
eval($m[0]);

/* Свежепосчитанная строка: planned уже упал в ноль — занятия прошли. */
$fresh = ['present' => 1590.0, 'all' => 1720.0, 'planned' => 0.0, 'lessons' => 30, 'ts' => '2026-09-09T22:00:00+03:00'];

/* --- 1. снимок, снятый вовремя: expect и метка времени переносятся --- */
$old = ['expect' => 1658.0, 'expectTs' => '2026-08-30T22:00:05+03:00'];
$r = alfa_expect_carry($old, $fresh);
ok('ожидалось перенесено', $r['expect'], 1658.0);
ok('и метка времени', $r['expectTs'], '2026-08-30T22:00:05+03:00');
yes('способа нет — и не выдумываем', !isset($r['expectSrc']));
ok('свежий факт не тронут', $r['present'], 1590.0);
ok('и planned остался нулём', $r['planned'], 0.0);

/* --- 2. ГЛАВНОЕ: реконструкция остаётся реконструкцией --- */
$old = ['expect' => 1234.0, 'expectTs' => '2026-09-09T10:00:00+03:00', 'expectSrc' => 'schedule'];
$r = alfa_expect_carry($old, $fresh);
ok('ожидалось перенесено', $r['expect'], 1234.0);
ok('способ тоже перенесён', $r['expectSrc'], 'schedule');
yes('то есть 🧩 не превращается в 🔒', ($r['expectSrc'] ?? '') === 'schedule',
    'без этого признака интерфейс подписал бы реконструкцию как снятый вовремя снимок');

/* --- 3. день не морозили: не переносим ничего --- */
/* ⚠️ Метки без самого числа означали бы «заморожено» там, где заморозки не было: столбец
   нарисовал бы замок над пустотой. */
$r = alfa_expect_carry(['expectTs' => '2026-09-01T22:00:00+03:00', 'expectSrc' => 'schedule'], $fresh);
yes('без expect метка времени не переносится', !isset($r['expectTs']));
yes('и способ тоже', !isset($r['expectSrc']));
ok('строка осталась собой', $r['lessons'], 30);

/* --- 4. старой строки нет вовсе (день считаем впервые) --- */
$r = alfa_expect_carry(null, $fresh);
ok('ничего не добавилось', count($r), count($fresh));
yes('и ожидания не появилось', !isset($r['expect']));

/* --- 5. expect равен нулю — это ЗНАЧЕНИЕ, а не отсутствие --- */
/* В этот день и не планировали: alfa_expect_freeze морозит такой день честным нулём, и он
   обязан пережить пересчёт. isset() на нуле истинен — проверяем, что не сравниваем с empty(). */
$r = alfa_expect_carry(['expect' => 0.0, 'expectTs' => '2026-08-30T22:00:00+03:00'], $fresh);
ok('нулевое ожидание перенесено', $r['expect'], 0.0);
ok('и его метка', $r['expectTs'], '2026-08-30T22:00:00+03:00');

/* --- 6. пересчёт не должен «оживлять» ожидание из свежей строки --- */
/* Если у новой строки уже есть expect (её собрали не с нуля), старая всё равно главнее:
   заморозка происходит один раз, и переголосовать её пересчётом нельзя. */
$r = alfa_expect_carry(['expect' => 1658.0], ['planned' => 900.0, 'expect' => 900.0]);
ok('старое ожидание сильнее нового', $r['expect'], 1658.0);

echo $bad ? "\n❌ ПРОВАЛЕНО: $bad\n" : "\n✅ всё сошлось\n";
exit($bad ? 1 : 0);
