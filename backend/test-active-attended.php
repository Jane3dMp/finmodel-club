<?php
// «Активные клиенты» в отчёте продажам = кто РЕАЛЬНО пришёл за неделю.
// Запуск: php backend/test-active-attended.php
//
// Решение Жанны 06.09.2026. Раньше считали иначе — все неархивные ученики базы Alfa
// (is_study=1, removed=0), то есть цифра мерила порядок в базе, а не посещаемость:
// ребёнок, переставший ходить в мае и не отправленный в архив, оставался «активным».
//
// Неделю можно считать только по id: пришедший в понедельник и в среду — один активный,
// а не два. Поэтому id пришедших копятся по дням, и неделя — это их объединение.
declare(strict_types=1);

$bad = 0;
function ok(string $name, $got, $want): void {
    global $bad;
    $good = $got === $want;
    if (!$good) $bad++;
    echo ($good ? "✓ " : "✗ ") . $name . ' = ' . json_encode($got, JSON_UNESCAPED_UNICODE)
       . ($good ? '' : ' ≠ ' . json_encode($want, JSON_UNESCAPED_UNICODE)) . "\n";
}
function yes(string $name, bool $cond, string $detail = ''): void {
    global $bad;
    if (!$cond) $bad++;
    echo ($cond ? "✓ " : "✗ ") . $name . ($cond || $detail === '' ? '' : ': ' . $detail) . "\n";
}

/* --- хранилище посещаемости в памяти вместо файла --- */
$ATT = [];
function alfa_attend_read(): array { global $ATT; return $ATT; }

/* --- вырезаем НАСТОЯЩУЮ функцию из lib.php --- */
$lib = file_get_contents(__DIR__ . '/../api/alfa/lib.php');
if (!preg_match('/\nfunction alfa_active_attended\(.*?\n\}/s', $lib, $m)) {
    echo "не найдено в lib.php: alfa_active_attended\n"; exit(1);
}
eval($m[0]);

$MON = '2026-08-31';        // неделя 31.08–06.09

/* ===== 1. один ребёнок за неделю считается один раз ===== */
$ATT = [
    '2026-08-31' => [101, 102, 103],
    '2026-09-01' => [101, 104],           // 101 пришёл второй раз
    '2026-09-02' => [],                   // законный «никто не пришёл»
    '2026-09-03' => [102, 105],
    '2026-09-04' => [106],
    '2026-09-05' => [101, 107, 108],
    '2026-09-06' => [108, 109],
];
$a = alfa_active_attended($MON);
ok('разных детей за неделю', $a['count'], 9);          // 101–109
ok('дней с данными — все семь', $a['days'], 7);
ok('источник назван', $a['src'], 'attend');
ok('неделя названа', $a['week'], $MON);

/* ===== 2. соседние недели не подмешиваются ===== */
$ATT['2026-08-30'] = [201, 202];          // воскресенье ДО недели
$ATT['2026-09-07'] = [203];               // понедельник ПОСЛЕ
ok('чужие дни не считаются', alfa_active_attended($MON)['count'], 9);

/* ===== 3. пустой день — это «никто», а отсутствующий — «не читали» =====
   Разница принципиальная: по четырём дням из семи нельзя отдавать число как недельное. */
unset($ATT['2026-09-05'], $ATT['2026-09-06']);
$a = alfa_active_attended($MON);
ok('дней с данными стало пять', $a['days'], 5);
ok('и в счёт вошли только они', $a['count'], 6);       // 101,102,103,104,105,106
$ATT['2026-09-02'] = [];
ok('пустой день данными считается', alfa_active_attended($MON)['days'], 5);

/* ===== 4. недели без данных вовсе ===== */
ok('чужая неделя — ноль', alfa_active_attended('2026-10-05')['count'], 0);
ok('и честно сказано, что дней нет', alfa_active_attended('2026-10-05')['days'], 0);

/* ===== 5. мусор в хранилище не роняет счёт ===== */
$ATT = ['2026-08-31' => [0, '102', null, 103, '0', 103]];
$a = alfa_active_attended($MON);
ok('нули и пустые id отброшены', $a['count'], 2);      // 102 и 103
ok('строковый id считается тем же числом', $a['days'], 1);

/* ===== 6. дневной сбор: id берутся только у ПРИШЕДШИХ =====
   Проверяем условие в alfa_realization_day по исходнику: id кладётся внутрь ветки is_attend,
   иначе в «активные» попали бы и те, кому занятие просто списали. */
yes('id пришедшего собирается внутри ветки is_attend',
    (bool)preg_match('/if \(\$att\) \{ \$present \+= \$c;[\s\S]{0,600}?\$attIds\[\$cid2\] = 1; \}/', $lib));
yes('наружу id уходят отдельным полем',
    strpos($lib, "'attendedIds' => array_map('intval', array_keys(\$attIds))") !== false);
yes('и записываются в своё хранилище, а не в дневное',
    strpos($lib, "\$att[\$r['date']] = array_values((array)(\$r['attendedIds'] ?? []));") !== false);
yes('отчёт продажам считает активных по посещаемости',
    strpos($lib, '$act = alfa_active_attended($mon);') !== false);
yes('и сравнивает с прошлой неделей только при том же способе счёта',
    strpos($lib, "(string)(\$prev['activeSrc'] ?? '') === (string)\$act['src']") !== false);

echo $bad ? "\n❌ провалов: $bad\n" : "\n✅ всё сошлось\n";
exit($bad ? 1 : 0);
